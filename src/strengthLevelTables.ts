export const BW_MIN = 110;
export const BW_MAX = 310;
export const BW_STEP = 10;
export const BW_REFERENCE = 150;

export type Row = [number, number, number, number];

function parse(table: string): Row[] {
  const rows = table
    .trim()
    .split('\n')
    .map((line) => line.trim().split('/').map((x) => (x === '<1' ? 1 : Number(x))) as Row);
  if (rows.length !== (BW_MAX - BW_MIN) / BW_STEP + 1 || rows.some((r) => r.length !== 4 || r.some((x) => !Number.isFinite(x)))) {
    throw new Error('strengthLevelTables: malformed table');
  }
  return rows;
}

const doubled = (rows: Row[]): Row[] => rows.map((r) => r.map((x) => x * 2) as Row);

