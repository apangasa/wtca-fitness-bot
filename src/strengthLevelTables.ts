export function inBodyweightRange(lb: number): boolean {
  return Number.isFinite(lb) && lb >= BW_MIN && lb <= BW_MAX;
}

/** The four anchors at a body weight: each column linear in body weight between rows, clamped to the table. */
export function tableAt(rows: Row[], bodyLb: number): Row {
  const b = Math.min(Math.max(bodyLb, BW_MIN), BW_MAX);
  const f = (b - BW_MIN) / BW_STEP;
  const i = Math.min(Math.floor(f), rows.length - 2);
  const t = f - i;
  const lo = rows[i]!;
  const hi = rows[i + 1]!;
  return lo.map((v, k) => v + (hi[k]! - v) * t) as Row;
}
